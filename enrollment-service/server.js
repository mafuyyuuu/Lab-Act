const express = require("express");

const app = express();
const PORT = 3003;
app.use(express.json());

// Classroom data is in memory and resets when this service restarts.
let enrollments = [
    {
        "id": 1,
        "studentId": 1,
        "courseId": 101,
        "semester": "1st Semester",
        "schoolYear": "2026-2027"
    }
];
let nextId = 2;
const fields = ["studentId", "courseId", "semester", "schoolYear"];

function validate(data) {
    const errors = [];
    if (!Number.isSafeInteger(data.studentId) || data.studentId <= 0) errors.push("studentId must be a positive integer");
    if (!Number.isSafeInteger(data.courseId) || data.courseId <= 0) errors.push("courseId must be a positive integer");
    if (typeof data.semester !== "string" || !data.semester.trim()) errors.push("semester must be a non-empty string");
    if (typeof data.schoolYear !== "string" || !data.schoolYear.trim()) errors.push("schoolYear must be a non-empty string");
    return errors;
}

function isObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

app.param("id", (req, res, next, value) => {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ message: "ID must be a positive integer" });
    }
    req.recordId = id;
    next();
});

// GET ALL
app.get("/enrollments", (req, res) => {
    res.status(200).json(enrollments);
});

// GET BY ID
app.get("/enrollments/:id", (req, res) => {
    const record = enrollments.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Enrollment not found" });
    res.status(200).json(record);
});

// CREATE: IDs are generated by the service.
app.post("/enrollments", (req, res) => {
    if (!isObject(req.body)) {
        return res.status(400).json({ message: "Provide a JSON object" });
    }
    const errors = validate(req.body);
    if (errors.length) return res.status(400).json({ message: "Invalid enrollment data", errors });
    const record = { id: nextId++ };
    for (const field of fields) record[field] = req.body[field];
    enrollments.push(record);
    res.status(201).json({ message: "Enrollment created successfully", enrollment: record });
});

// UPDATE: omitted fields retain their values; IDs cannot be changed.
app.put("/enrollments/:id", (req, res) => {
    const record = enrollments.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Enrollment not found" });
    if (!isObject(req.body) || !fields.some(field => Object.hasOwn(req.body, field))) {
        return res.status(400).json({ message: "Provide at least one editable field" });
    }
    const updated = { ...record };
    for (const field of fields) {
        if (Object.hasOwn(req.body, field)) updated[field] = req.body[field];
    }
    const errors = validate(updated);
    if (errors.length) return res.status(400).json({ message: "Invalid enrollment data", errors });
    Object.assign(record, updated);
    res.status(200).json({ message: "Enrollment updated successfully", enrollment: record });
});

// DELETE
app.delete("/enrollments/:id", (req, res) => {
    const index = enrollments.findIndex(item => item.id === req.recordId);
    if (index === -1) return res.status(404).json({ message: "Enrollment not found" });
    const [record] = enrollments.splice(index, 1);
    res.status(200).json({ message: "Enrollment deleted successfully", enrollment: record });
});

// Preserve the existing Group 10 integration route, with the field name fixed.
// Configure a reachable cloud URL when this service is deployed separately.
app.get("/student-enrollment/:id", async (req, res) => {
    const enrollment = enrollments.find(item => item.id === req.recordId);
    if (!enrollment) return res.status(404).json({ message: "Enrollment not found" });
    const baseUrl = process.env.STUDENT_SERVICE_URL || "http://localhost:3001";
    try {
        const response = await fetch(
            `${baseUrl.replace(/\/$/, "")}/students/${enrollment.studentId}`,
            { signal: AbortSignal.timeout(5000) }
        );
        if (!response.ok) {
            return res.status(response.status === 404 ? 404 : 502).json({
                message: response.status === 404
                    ? "Student not found"
                    : "Student service returned an error"
            });
        }
        const student = await response.json();
        res.status(200).json({ enrollment, student });
    } catch (error) {
        console.error("Student lookup failed:", error.message);
        res.status(502).json({ message: "Cannot retrieve information from student service" });
    }
});

// Malformed JSON and unexpected errors return JSON responses.
app.use((error, req, res, next) => {
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Invalid JSON body" });
    }
    console.error(error.message);
    res.status(500).json({ message: "Internal server error" });
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Enrollment Service running on port ${PORT}`);
});
