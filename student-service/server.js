const express = require("express");

const app = express();
const PORT = 3001;
app.use(express.json());

// Classroom data is in memory and resets when this service restarts.
let students = [
    {
        "id": 1,
        "name": "Juan Dela Cruz",
        "course": "BSIT",
        "year": 4
    },
    {
        "id": 2,
        "name": "Maria Santos",
        "course": "BSCS",
        "year": 3
    },
    {
        "id": 3,
        "name": "Pedro Reyes",
        "course": "BSIT",
        "year": 2
    }
];
let nextId = 4;
const fields = ["name", "course", "year"];

function validate(data) {
    const errors = [];
    if (typeof data.name !== "string" || !data.name.trim()) errors.push("name must be a non-empty string");
    if (typeof data.course !== "string" || !data.course.trim()) errors.push("course must be a non-empty string");
    if (!Number.isSafeInteger(data.year) || data.year <= 0) errors.push("year must be a positive integer");
    return errors;
}

function isObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

app.param("id", (req, res, next, value) => {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ message: "ID must be a positive integer" });
    }
    req.recordId = id;
    next();
});

// GET ALL
app.get("/students", (req, res) => {
    res.status(200).json(students);
});

// GET BY ID
app.get("/students/:id", (req, res) => {
    const record = students.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Student not found" });
    res.status(200).json(record);
});

// CREATE: IDs are generated by the service.
app.post("/students", (req, res) => {
    if (!isObject(req.body)) {
        return res.status(400).json({ message: "Provide a JSON object" });
    }
    const errors = validate(req.body);
    if (errors.length) return res.status(400).json({ message: "Invalid student data", errors });
    const record = { id: nextId++ };
    for (const field of fields) record[field] = req.body[field];
    students.push(record);
    res.status(201).json({ message: "Student added successfully", student: record });
});

// UPDATE: omitted fields retain their values; IDs cannot be changed.
app.put("/students/:id", (req, res) => {
    const record = students.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Student not found" });
    if (!isObject(req.body) || !fields.some(field => Object.hasOwn(req.body, field))) {
        return res.status(400).json({ message: "Provide at least one editable field" });
    }
    const updated = { ...record };
    for (const field of fields) {
        if (Object.hasOwn(req.body, field)) updated[field] = req.body[field];
    }
    const errors = validate(updated);
    if (errors.length) return res.status(400).json({ message: "Invalid student data", errors });
    Object.assign(record, updated);
    res.status(200).json({ message: "Student updated successfully", student: record });
});

// DELETE
app.delete("/students/:id", (req, res) => {
    const index = students.findIndex(item => item.id === req.recordId);
    if (index === -1) return res.status(404).json({ message: "Student not found" });
    const [record] = students.splice(index, 1);
    res.status(200).json({ message: "Student deleted successfully", student: record });
});

// Malformed JSON and unexpected errors return JSON responses.
app.use((error, req, res, next) => {
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Invalid JSON body" });
    }
    console.error(error.message);
    res.status(500).json({ message: "Internal server error" });
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Student Service running on port ${PORT}`);
});
