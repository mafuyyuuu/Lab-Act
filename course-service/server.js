const express = require("express");

const app = express();
const PORT = 3002;
app.use(express.json());

// Classroom data is in memory and resets when this service restarts.
let courses = [
    {
        "id": 101,
        "code": "IT204",
        "title": "System Integration and Architecture 2",
        "units": 3
    }
];
let nextId = 102;
const fields = ["code", "title", "units"];

function validate(data) {
    const errors = [];
    if (typeof data.code !== "string" || !data.code.trim()) errors.push("code must be a non-empty string");
    if (typeof data.title !== "string" || !data.title.trim()) errors.push("title must be a non-empty string");
    if (typeof data.units !== "number" || !Number.isFinite(data.units) || data.units <= 0) errors.push("units must be a positive number");
    return errors;
}

function isObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

app.param("id", (req, res, next, value) => {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ message: "ID must be a positive integer" });
    }
    req.recordId = id;
    next();
});

// GET ALL
app.get("/courses", (req, res) => {
    res.status(200).json(courses);
});

// GET BY ID
app.get("/courses/:id", (req, res) => {
    const record = courses.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Course not found" });
    res.status(200).json(record);
});

// CREATE: IDs are generated by the service.
app.post("/courses", (req, res) => {
    if (!isObject(req.body)) {
        return res.status(400).json({ message: "Provide a JSON object" });
    }
    const errors = validate(req.body);
    if (errors.length) return res.status(400).json({ message: "Invalid course data", errors });
    const record = { id: nextId++ };
    for (const field of fields) record[field] = req.body[field];
    courses.push(record);
    res.status(201).json({ message: "Course added successfully", course: record });
});

// UPDATE: omitted fields retain their values; IDs cannot be changed.
app.put("/courses/:id", (req, res) => {
    const record = courses.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Course not found" });
    if (!isObject(req.body) || !fields.some(field => Object.hasOwn(req.body, field))) {
        return res.status(400).json({ message: "Provide at least one editable field" });
    }
    const updated = { ...record };
    for (const field of fields) {
        if (Object.hasOwn(req.body, field)) updated[field] = req.body[field];
    }
    const errors = validate(updated);
    if (errors.length) return res.status(400).json({ message: "Invalid course data", errors });
    Object.assign(record, updated);
    res.status(200).json({ message: "Course updated successfully", course: record });
});

// DELETE
app.delete("/courses/:id", (req, res) => {
    const index = courses.findIndex(item => item.id === req.recordId);
    if (index === -1) return res.status(404).json({ message: "Course not found" });
    const [record] = courses.splice(index, 1);
    res.status(200).json({ message: "Course deleted successfully", course: record });
});

// Malformed JSON and unexpected errors return JSON responses.
app.use((error, req, res, next) => {
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Invalid JSON body" });
    }
    console.error(error.message);
    res.status(500).json({ message: "Internal server error" });
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Course Service running on port ${PORT}`);
});
