const express = require("express");

const app = express();
const PORT = 3006;
app.use(express.json());

// Classroom data is in memory and resets when this service restarts.
let faculty = [
    {
        "id": 1,
        "name": "Maria Santos",
        "department": "Information Technology",
        "position": "Instructor"
    }
];
let nextId = 2;
const fields = ["name", "department", "position"];

function validate(data) {
    const errors = [];
    if (typeof data.name !== "string" || !data.name.trim()) errors.push("name must be a non-empty string");
    if (typeof data.department !== "string" || !data.department.trim()) errors.push("department must be a non-empty string");
    if (typeof data.position !== "string" || !data.position.trim()) errors.push("position must be a non-empty string");
    return errors;
}

function isObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

app.param("id", (req, res, next, value) => {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ message: "ID must be a positive integer" });
    }
    req.recordId = id;
    next();
});

// GET ALL
app.get("/faculty", (req, res) => {
    res.status(200).json(faculty);
});

// GET BY ID
app.get("/faculty/:id", (req, res) => {
    const record = faculty.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Faculty member not found" });
    res.status(200).json(record);
});

// CREATE: IDs are generated by the service.
app.post("/faculty", (req, res) => {
    if (!isObject(req.body)) {
        return res.status(400).json({ message: "Provide a JSON object" });
    }
    const errors = validate(req.body);
    if (errors.length) return res.status(400).json({ message: "Invalid faculty data", errors });
    const record = { id: nextId++ };
    for (const field of fields) record[field] = req.body[field];
    faculty.push(record);
    res.status(201).json({ message: "Faculty member added successfully", faculty: record });
});

// UPDATE: omitted fields retain their values; IDs cannot be changed.
app.put("/faculty/:id", (req, res) => {
    const record = faculty.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Faculty member not found" });
    if (!isObject(req.body) || !fields.some(field => Object.hasOwn(req.body, field))) {
        return res.status(400).json({ message: "Provide at least one editable field" });
    }
    const updated = { ...record };
    for (const field of fields) {
        if (Object.hasOwn(req.body, field)) updated[field] = req.body[field];
    }
    const errors = validate(updated);
    if (errors.length) return res.status(400).json({ message: "Invalid faculty data", errors });
    Object.assign(record, updated);
    res.status(200).json({ message: "Faculty member updated successfully", faculty: record });
});

// DELETE
app.delete("/faculty/:id", (req, res) => {
    const index = faculty.findIndex(item => item.id === req.recordId);
    if (index === -1) return res.status(404).json({ message: "Faculty member not found" });
    const [record] = faculty.splice(index, 1);
    res.status(200).json({ message: "Faculty member deleted successfully", faculty: record });
});

// Malformed JSON and unexpected errors return JSON responses.
app.use((error, req, res, next) => {
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Invalid JSON body" });
    }
    console.error(error.message);
    res.status(500).json({ message: "Internal server error" });
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Faculty Service running on port ${PORT}`);
});
