const express = require("express");

const app = express();
const PORT = 3004;
app.use(express.json());

// Classroom data is in memory and resets when this service restarts.
let payments = [
    {
        "id": 1001,
        "studentId": 1,
        "amount": 25000,
        "status": "PAID"
    }
];
let nextId = 1002;
const fields = ["studentId", "amount", "status"];

function validate(data) {
    const errors = [];
    if (!Number.isSafeInteger(data.studentId) || data.studentId <= 0) errors.push("studentId must be a positive integer");
    if (typeof data.amount !== "number" || !Number.isFinite(data.amount) || data.amount < 0) errors.push("amount must be a non-negative number");
    if (typeof data.status !== "string" || !data.status.trim()) errors.push("status must be a non-empty string");
    return errors;
}

function isObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

app.param("id", (req, res, next, value) => {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id <= 0) {
        return res.status(400).json({ message: "ID must be a positive integer" });
    }
    req.recordId = id;
    next();
});

// GET ALL
app.get("/payments", (req, res) => {
    res.status(200).json(payments);
});

// GET BY ID
app.get("/payments/:id", (req, res) => {
    const record = payments.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Payment not found" });
    res.status(200).json(record);
});

// CREATE: IDs are generated by the service.
app.post("/payments", (req, res) => {
    if (!isObject(req.body)) {
        return res.status(400).json({ message: "Provide a JSON object" });
    }
    const errors = validate(req.body);
    if (errors.length) return res.status(400).json({ message: "Invalid payment data", errors });
    const record = { id: nextId++ };
    for (const field of fields) record[field] = req.body[field];
    payments.push(record);
    res.status(201).json({ message: "Payment added successfully", payment: record });
});

// UPDATE: omitted fields retain their values; IDs cannot be changed.
app.put("/payments/:id", (req, res) => {
    const record = payments.find(item => item.id === req.recordId);
    if (!record) return res.status(404).json({ message: "Payment not found" });
    if (!isObject(req.body) || !fields.some(field => Object.hasOwn(req.body, field))) {
        return res.status(400).json({ message: "Provide at least one editable field" });
    }
    const updated = { ...record };
    for (const field of fields) {
        if (Object.hasOwn(req.body, field)) updated[field] = req.body[field];
    }
    const errors = validate(updated);
    if (errors.length) return res.status(400).json({ message: "Invalid payment data", errors });
    Object.assign(record, updated);
    res.status(200).json({ message: "Payment updated successfully", payment: record });
});

// Final scenario Step E: this parameter is a STUDENT ID, not a payment ID.
app.get("/payments/student/:id", (req, res) => {
    const matches = payments.filter(item => item.studentId === req.recordId);
    if (!matches.length) {
        return res.status(404).json({ message: "Payment not found for student" });
    }
    // For this lab, show the newest payment record for that student.
    // This does not calculate an outstanding balance or aggregate installments.
    res.status(200).json(matches[matches.length - 1]);
});

// Malformed JSON and unexpected errors return JSON responses.
app.use((error, req, res, next) => {
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Invalid JSON body" });
    }
    console.error(error.message);
    res.status(500).json({ message: "Internal server error" });
});

app.listen(PORT, "0.0.0.0", () => {
    console.log(`Payment Service running on port ${PORT}`);
});
